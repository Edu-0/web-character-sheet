import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';
import {editorArea,editorCommand} from '../helpers/editor-workspace-nav.js';

test('0.8 jornada completa: vazio, primeiro campo, recuperar rascunho, exportar, instalar e jogar', async ({page}) => {
  test.setTimeout(90000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');await expect(page.locator('#shell-current-system')).toHaveText('D&D 5e (2024)');
  await page.getByRole('button',{name:'Sistemas',exact:true}).click();
  await page.getByRole('button',{name:'Criar pacote',exact:true}).click();
  await expect(page.locator('#editor-preview-status')).toContainText('Ensaio da revisão');
  await page.getByLabel('Nome do sistema',{exact:true}).fill('Jornadas da Aurora');
  await editorArea(page,'review');
  await page.getByRole('button',{name:'Localizar campo',exact:true}).click();
  await page.locator('[data-property="/system/name"]').getByRole('button',{name:'Aplicar campo',exact:true}).click();
  await editorArea(page,'sheet');
  await page.getByRole('button',{name:'Adicionar primeiro elemento',exact:true}).click();
  const flow=page.locator('.workspace-first-element');
  await flow.getByLabel('Nome mostrado na ficha',{exact:true}).fill('Nome da jornada');
  await flow.getByRole('button',{name:'Revisar inclusão',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'Confirmar alteração',exact:true}).click();
  const authored=JSON.parse(await page.locator('#editor-json').inputValue());
  expect(authored.system.dataDefinitions).toHaveLength(1);
  await editorCommand(page,'Salvar rascunho');
  await expect(page.locator('#editor-status')).toContainText('Rascunho salvo');
  await page.reload();
  await page.getByRole('button',{name:'Recuperar rascunho',exact:true}).click();
  await expect(page.locator('#editor-preview-status')).toContainText('Ensaio da revisão');
  expect(JSON.parse(await page.locator('#editor-json').inputValue())).toEqual(authored);
  await editorArea(page,'test');
  const frame=page.frameLocator('.editor-preview-frame:not([hidden])');
  await frame.getByLabel('Nome da jornada',{exact:true}).fill('Só no ensaio');
  expect(JSON.parse(await page.locator('#editor-json').inputValue())).toEqual(authored);
  const downloading=page.waitForEvent('download');await editorCommand(page,'Exportar pacote');
  const exported=JSON.parse(await readFile(await (await downloading).path(),'utf8'));
  expect(exported).toEqual(authored);
  await editorCommand(page,'Aplicar pacote');
  await page.getByRole('button',{name:'Confirmar aplicação',exact:true}).click();
  await expect(page.locator('#editor-application-status')).toContainText('Pacote aplicado');
  await editorCommand(page,'Sair do editor');
  await page.locator('#systems-list .library-card').filter({hasText:'Jornadas da Aurora'}).getByRole('button',{name:'Abrir',exact:true}).click();
  await expect(page.locator('#shell-current-system')).toHaveText('Jornadas da Aurora');
  const previous=await page.evaluate(async()=>(await import('/js/state.js')).state.get().meta.id);
  await page.getByRole('button',{name:'Personagens',exact:true}).click();
  await page.getByRole('button',{name:'Novo personagem',exact:true}).click();
  await expect.poll(()=>page.evaluate(async()=>(await import('/js/state.js')).state.get().meta.id)).not.toBe(previous);
  const input=page.locator('#generic-sheet-host').getByLabel('Nome da jornada',{exact:true});
  await expect(input).not.toHaveValue('Só no ensaio');
  await input.fill('Travessia do Norte');
  await page.getByRole('button',{name:'Salvar',exact:true}).click();
  await expect(page.locator('#save-indicator')).toHaveText('Salvo');
  await page.reload();await expect(input).toHaveValue('Travessia do Norte');
  const characterDownload=page.waitForEvent('download');await page.locator('#btn-export').click();
  const character=JSON.parse(await readFile(await (await characterDownload).path(),'utf8'));
  expect(character.meta.system).toBe(authored.system.id);
  expect(JSON.stringify(character)).toContain('Travessia do Norte');
  expect(errors).toEqual([]);
});
